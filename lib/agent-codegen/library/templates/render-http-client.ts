// Deterministic renderer — LibraryFormFields + LLM-emitted methods+types
// → a single TypeScript HTTP client module.
//
// Output is a self-contained file:
//   - banner with provenance
//   - auth helpers (header builders) chosen by authStyle
//   - requestUrl(path, params) for :id substitution
//   - ClientApiError class for non-2xx surfacing
//   - shared type exports
//   - one async function per LLM-emitted method
//
// The MVP emits ONE file (lib/generated/<name>/client.ts). Per-method file
// split + types.ts split are Phase 2.5 polish (research doc §B.4 LIB STAGE 3).

import type { LibraryFormFields, LibraryGenerationOutput, LibMethod } from '../lib-spec-types';

export type RenderLibraryInput = {
  form: LibraryFormFields;
  output: LibraryGenerationOutput;
  generatedAt?: string;
  generatedBy?: string;
};

export type RenderLibraryResult = {
  suggestedPath: string;
  content: string;
  /** Suggested AO TOOL_REGISTRY entries the operator can paste. */
  registrySuggestion: Array<{
    id: string;
    importFrom: string;
    importName: string;
    signature: string;
    summary: string;
  }>;
};

export function renderHttpClient({
  form,
  output,
  generatedAt = new Date().toISOString(),
  generatedBy = 'AO library codegen',
}: RenderLibraryInput): RenderLibraryResult {
  const sharedTypeBlock = output.sharedTypes
    .map((t) => t.tsDefinition.trim())
    .join('\n\n');

  const methodBlock = output.methods.map((m) => renderMethod(m)).join('\n\n');

  const content = `// lib/generated/${form.name}/client.ts
//
// ${form.description}
//
// Base URL:    ${form.baseUrl}
// Auth style:  ${form.authStyle}
// Env vars:    ${form.envVarsRequired.join(', ') || '(none)'}
//
// Generated by ${generatedBy} at ${generatedAt}.
// Do not hand-edit — regenerate from the seed instead.

${renderEnvBlock(form)}

${renderAuthHelpers(form)}

${renderUrlHelper()}

${renderErrorClass()}

${sharedTypeBlock || '// (no shared types)'}

${methodBlock}
`;

  const registrySuggestion = output.methods.map((m) => ({
    id: `${form.name}.${m.name}`,
    importFrom: `@/lib/generated/${form.name}/client`,
    importName: m.name,
    signature: `${m.name}(${m.paramsType}): ${m.returnType}`,
    summary: m.description,
  }));

  return {
    suggestedPath: `lib/generated/${form.name}/client.ts`,
    content,
    registrySuggestion,
  };
}

function renderEnvBlock(form: LibraryFormFields): string {
  if (form.envVarsRequired.length === 0) {
    return `const BASE_URL = '${form.baseUrl}';`;
  }
  const lines = form.envVarsRequired.map((v) => {
    if (v.endsWith('_BASE_URL'))
      return `const BASE_URL = process.env.${v} ?? '${form.baseUrl}';`;
    if (v.endsWith('_API_KEY') || v.endsWith('_TOKEN'))
      return `const ${v} = process.env.${v} ?? '';`;
    return `const ${v} = process.env.${v} ?? '';`;
  });
  return lines.join('\n');
}

function renderAuthHelpers(form: LibraryFormFields): string {
  switch (form.authStyle) {
    case 'bearer': {
      const tokenVar = form.envVarsRequired.find((v) => v.endsWith('_API_KEY') || v.endsWith('_TOKEN')) ?? 'TOKEN';
      return `function authHeaders(): Record<string, string> {
  return {
    'Authorization': \`Bearer \${${tokenVar}}\`,
    'Content-Type': 'application/json',
  };
}`;
    }
    case 'api-key': {
      const keyVar = form.envVarsRequired.find((v) => v.endsWith('_API_KEY')) ?? 'API_KEY';
      return `function authHeaders(): Record<string, string> {
  return {
    'x-api-key': ${keyVar},
    'Content-Type': 'application/json',
  };
}`;
    }
    case 'basic':
      return `function authHeaders(): Record<string, string> {
  // TODO: populate basic-auth header from your two env vars
  return { 'Content-Type': 'application/json' };
}`;
    case 'none':
    default:
      return `function authHeaders(): Record<string, string> {
  return { 'Content-Type': 'application/json' };
}`;
  }
}

function renderUrlHelper(): string {
  return `function requestUrl(path: string, pathParams?: Record<string, string | number>): string {
  let resolved = path;
  if (pathParams) {
    for (const [k, v] of Object.entries(pathParams)) {
      resolved = resolved.replace(\`:\${k}\`, encodeURIComponent(String(v)));
    }
  }
  return BASE_URL + resolved;
}`;
}

function renderErrorClass(): string {
  return `export class ClientApiError extends Error {
  constructor(public readonly status: number, public readonly bodyText: string) {
    super(\`HTTP \${status}: \${bodyText.slice(0, 200)}\`);
    this.name = 'ClientApiError';
  }
  get isClientError(): boolean {
    return this.status >= 400 && this.status < 500;
  }
}`;
}

function renderMethod(m: LibMethod): string {
  // TS1064 guard — async functions MUST return Promise<T>. The LLM
  // sometimes emits a bare type (`InviteCandidateResponse`) instead of
  // `Promise<InviteCandidateResponse>`. Wrap defensively so the generator
  // never emits a TS1064 even on a slightly-misbehaving model.
  const returnType = ensurePromise(m.returnType);
  return `/** ${m.description} */
export async function ${m.name}(params: ${m.paramsType}): ${returnType} {
  ${m.body.trim().split('\n').join('\n  ')}
}`;
}

/** Wrap `T` as `Promise<T>` unless it's already a Promise. */
function ensurePromise(returnType: string): string {
  const trimmed = returnType.trim();
  if (/^Promise\s*</.test(trimmed)) return trimmed;
  return `Promise<${trimmed}>`;
}
